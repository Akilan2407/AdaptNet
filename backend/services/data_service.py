    @staticmethod
    def _load_df(filepath: Path) -> Optional[pd.DataFrame]:
        """Load CSV into a DataFrame, using the in-memory cache when possible."""
        if not filepath.exists():
            logger.warning("Data file not found: %s", filepath)
            return None
        cached = _get_cached_df(filepath)
        if cached is not None:
            return cached
        try:
            df = pd.read_csv(filepath)
            _set_cached_df(filepath, df)
            return df
        except Exception as e:
            logger.error("Failed to read CSV %s: %s", filepath, e)
            return None

    @staticmethod
    def read_csv(
        filepath: Union[str, Path],
        limit: Optional[int] = None,
        offset: Optional[int] = None,
        filters: Optional[Dict[str, Any]] = None,
        sort_by: Optional[str] = None,
        sort_order: str = "asc",
    ) -> Tuple[List[Dict[str, Any]], int]:
        """Read CSV with optional filtering, sorting, limit, and offset.

        Returns:
            Tuple of (list_of_records, total_matching_records).
        """
        p = Path(filepath)
        df = DataService._load_df(p)
        if df is None or df.empty:
            return [], 0

        # Copy so we don't mutate the cached frame
        df = df.copy()

        # Apply column filters
        if filters:
            for k, v in filters.items():
                if k in df.columns and v is not None:
                    if df[k].dtype == "object":
                        df = df[df[k].astype(str).str.upper() == str(v).strip().upper()]
                    else:
                        try:
                            df = df[df[k] == type(df[k].iloc[0])(v)]
                        except Exception:
                            df = df[df[k] == v]

        # Apply sorting
        if sort_by and sort_by in df.columns:
            ascending = sort_order.lower() != "desc"
            try:
                df = df.sort_values(by=sort_by, ascending=ascending, na_position="last")
            except Exception as e:
                logger.warning("Sort by '%s' failed: %s", sort_by, e)

        total = len(df)

        # Apply pagination
        start = offset or 0
        end = start + limit if limit is not None else None
        df_page = df.iloc[start:end]

        records = [sanitize_value(r) for r in df_page.to_dict(orient="records")]
        return records, total

    @staticmethod
    def read_json(filepath: Union[str, Path]) -> Optional[Dict[str, Any]]:
        """Read JSON file safely, with mtime-based caching."""
        p = Path(filepath)
        if not p.exists():
            logger.warning("JSON file not found: %s", p)
            return None
        cached = _get_cached_json(p)
        if cached is not None:
            return cached
        try:
            with open(p, "r", encoding="utf-8") as f:
                data = json.load(f)
            result = sanitize_value(data)
            _set_cached_json(p, result)
            return result
        except Exception as e:
            logger.error("Failed to read JSON %s: %s", p, e)
            return None

    @staticmethod
    def read_jsonl(
        filepath: Union[str, Path],
        limit: Optional[int] = None,
        offset: Optional[int] = None,
        id_field: Optional[str] = None,
        target_id: Optional[str] = None,
        filters: Optional[Dict[str, Any]] = None,
    ) -> Tuple[List[Dict[str, Any]], int]:
        """Read JSON Lines file with optional ID search, filtering, and pagination."""
        p = Path(filepath)
        if not p.exists():
            logger.warning("JSONL file not found: %s", p)
            return [], 0

        try:
            matched_records: List[Dict[str, Any]] = []
            with open(p, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        record = json.loads(line)
                        # ID-based lookup
                        if id_field and target_id is not None:
                            if str(record.get(id_field, "")).strip().upper() != str(target_id).strip().upper():
                                continue
                        # Field filters
                        if filters:
                            match = True
                            for k, v in filters.items():
                                if str(record.get(k, "")).strip().upper() != str(v).strip().upper():
                                    match = False
                                    break
                            if not match:
                                continue
                        matched_records.append(record)
                    except Exception:
                        pass

            total = len(matched_records)
            start = offset or 0
            end = start + limit if limit is not None else None
            page = matched_records[start:end]
            return [sanitize_value(r) for r in page], total
        except Exception as e:
            logger.error("Failed to read JSONL %s: %s", p, e)
            return [], 0

