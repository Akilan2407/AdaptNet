    @classmethod
    def get_monitoring_summary(cls) -> Dict[str, Any]:
        """Compute enhanced summary statistics for network telemetry."""
        target_csv = FEATURES_CSV if FEATURES_CSV.exists() else MONITORING_METRICS_CSV
        df = DataService._load_df(target_csv)
        if df is None or df.empty:
            return {"total_records": 0, "status": "unavailable"}

        try:
            def safe_mean(col: str) -> Optional[float]:
                if col not in df.columns:
                    return None
                series = pd.to_numeric(df[col], errors="coerce")
                val = series.mean()
                return round(float(val), 4) if pd.notna(val) else None

            def safe_max(col: str) -> Optional[float]:
                if col not in df.columns:
                    return None
                series = pd.to_numeric(df[col], errors="coerce")
                val = series.max()
                return round(float(val), 4) if pd.notna(val) else None

            def safe_min(col: str) -> Optional[float]:
                if col not in df.columns:
                    return None
                series = pd.to_numeric(df[col], errors="coerce")
                val = series.min()
                return round(float(val), 4) if pd.notna(val) else None

            # Per-device breakdown
            per_device: List[Dict[str, Any]] = []
            if "device_id" in df.columns:
                for dev, grp in df.groupby("device_id"):
                    throughput = pd.to_numeric(grp.get("throughput_mbps", pd.Series(dtype=float)), errors="coerce")
                    per_device.append({
                        "device_id": dev,
                        "flow_count": int(len(grp)),
                        "avg_throughput_mbps": round(float(throughput.mean()), 4) if pd.notna(throughput.mean()) else 0.0,
                        "max_throughput_mbps": round(float(throughput.max()), 4) if pd.notna(throughput.max()) else 0.0,
                        "total_flow_count": int(grp["total_flow_count"].sum()) if "total_flow_count" in grp.columns else 0,
                    })

            # Protocol distribution
            protocol_dist: Dict[str, int] = {}
            if "protocol" in df.columns:
                for proto, cnt in df["protocol"].value_counts().items():
                    protocol_dist[str(proto)] = int(cnt)

            summary = {
                "total_records": int(len(df)),
                "unique_devices": int(df["device_id"].nunique()) if "device_id" in df.columns else 0,
                "avg_throughput_mbps": safe_mean("throughput_mbps"),
                "avg_rtt_ms": safe_mean("rtt_ms"),
                "avg_packet_loss_percent": safe_mean("packet_loss_percent"),
                "max_throughput_mbps": safe_max("throughput_mbps"),
                "min_throughput_mbps": safe_min("throughput_mbps"),
                "avg_active_connections": safe_mean("active_connections"),
                "time_range": {
                    "start": str(df["timestamp"].min()) if "timestamp" in df.columns else None,
                    "end": str(df["timestamp"].max()) if "timestamp" in df.columns else None,
                },
                "protocol_distribution": protocol_dist,
                "per_device": per_device,
            }
            return sanitize_value(summary)
        except Exception as e:
            logger.error("Error computing monitoring summary: %s", e)
            return {"total_records": 0, "error": str(e)}

