# ---------------------------------------------------------------------------
# In-memory CSV/JSON cache
# ---------------------------------------------------------------------------
_cache_lock = threading.Lock()
_csv_cache: Dict[str, Tuple[float, pd.DataFrame]] = {}   # path → (mtime, df)
_json_cache: Dict[str, Tuple[float, Any]] = {}            # path → (mtime, obj)


def _get_cached_df(path: Path) -> Optional[pd.DataFrame]:
    """Return a cached DataFrame if the file has not changed, else None."""
    key = str(path)
    try:
        mtime = path.stat().st_mtime
    except OSError:
        return None
    with _cache_lock:
        entry = _csv_cache.get(key)
        if entry and entry[0] == mtime:
            return entry[1]
    return None


def _set_cached_df(path: Path, df: pd.DataFrame) -> None:
    key = str(path)
    try:
        mtime = path.stat().st_mtime
    except OSError:
        return
    with _cache_lock:
        _csv_cache[key] = (mtime, df)


def _get_cached_json(path: Path) -> Optional[Any]:
    key = str(path)
    try:
        mtime = path.stat().st_mtime
    except OSError:
        return None
    with _cache_lock:
        entry = _json_cache.get(key)
        if entry and entry[0] == mtime:
            return entry[1]
    return None


def _set_cached_json(path: Path, obj: Any) -> None:
    key = str(path)
    try:
        mtime = path.stat().st_mtime
    except OSError:
        return
    with _cache_lock:
        _json_cache[key] = (mtime, obj)


