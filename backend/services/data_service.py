    # 1. Monitoring & Features
    @classmethod
    def get_monitoring_flows(
        cls,
        limit: Optional[int] = 50,
        offset: Optional[int] = 0,
        device_id: Optional[str] = None,
    ) -> Tuple[List[Dict[str, Any]], int]:
        """Get network monitoring telemetry flows."""
        # Prefer network_features.csv if available for enriched features, fallback to network_metrics.csv
        target_csv = FEATURES_CSV if FEATURES_CSV.exists() else MONITORING_METRICS_CSV
        filters = {}
        if device_id:
            filters["device_id"] = device_id
        return cls.read_csv(target_csv, limit=limit, offset=offset, filters=filters)

    @classmethod
    def get_monitoring_summary(cls) -> Dict[str, Any]:
        """Compute summary statistics for network telemetry."""
        target_csv = FEATURES_CSV if FEATURES_CSV.exists() else MONITORING_METRICS_CSV
        if not target_csv.exists():
            return {"total_records": 0, "status": "unavailable"}

        try:
            df = pd.read_csv(target_csv)
            if df.empty:
                return {"total_records": 0}

            summary = {
                "total_records": len(df),
                "unique_devices": int(df["device_id"].nunique()) if "device_id" in df else 0,
                "avg_throughput_mbps": round(float(df["throughput_mbps"].mean()), 2) if "throughput_mbps" in df else 0.0,
                "avg_rtt_ms": round(float(df["rtt_ms"].mean()), 2) if "rtt_ms" in df else 0.0,
                "avg_packet_loss_percent": round(float(df["packet_loss_percent"].mean()), 2) if "packet_loss_percent" in df else 0.0,
                "max_throughput_mbps": round(float(df["throughput_mbps"].max()), 2) if "throughput_mbps" in df else 0.0,
            }
            return sanitize_value(summary)
        except Exception as e:
            logger.error("Error computing monitoring summary: %s", e)
            return {"total_records": 0, "error": str(e)}

