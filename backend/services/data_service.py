    # -------------------------------------------------------------------------

    @classmethod
    def search_flows(
        cls,
        query: str,
        limit: int = 20,
    ) -> List[Dict[str, Any]]:
        """Search flow records by device_id, src_ip, dst_ip, or flow_id."""
        if not query or len(query) < 2:
            return []
        target_csv = FEATURES_CSV if FEATURES_CSV.exists() else MONITORING_METRICS_CSV
        df = DataService._load_df(target_csv)
        if df is None or df.empty:
            return []

        q = query.strip().lower()
        search_cols = ["device_id", "src_ip", "dst_ip", "flow_id", "protocol"]
        mask = pd.Series([False] * len(df), index=df.index)
        for col in search_cols:
            if col in df.columns:
                mask |= df[col].astype(str).str.lower().str.contains(q, na=False)

        results = df[mask].head(limit)
        return [sanitize_value(r) for r in results.to_dict(orient="records")]
