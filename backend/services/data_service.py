    # -------------------------------------------------------------------------
    # Core File Readers
    # -------------------------------------------------------------------------

    @staticmethod
    def read_csv(
        filepath: Union[str, Path],
        limit: Optional[int] = None,
        offset: Optional[int] = None,
        filters: Optional[Dict[str, Any]] = None,
    ) -> Tuple[List[Dict[str, Any]], int]:
        """Read CSV file with optional filtering, limit, and offset.

        Returns:
            Tuple of (list_of_records, total_matching_records).
        """
        p = Path(filepath)
        if not p.exists():
            logger.warning("Data file not found: %s", p)
            return [], 0

        try:
            df = pd.read_csv(p)
            if df.empty:
                return [], 0

            # Apply filters if provided
            if filters:
                for k, v in filters.items():
                    if k in df.columns and v is not None:
                        # Case-insensitive string matching if applicable
                        if df[k].dtype == "object":
                            df = df[df[k].astype(str).str.upper() == str(v).strip().upper()]
                        else:
                            df = df[df[k] == v]

            total = len(df)

            # Apply pagination
            start = offset or 0
            if limit is not None:
                end = start + limit
                df_page = df.iloc[start:end]
            else:
                df_page = df.iloc[start:]

            records = [sanitize_value(r) for r in df_page.to_dict(orient="records")]
            return records, total
        except Exception as e:
            logger.error("Failed to read CSV %s: %s", p, e)
            return [], 0

    @staticmethod
    def read_json(filepath: Union[str, Path]) -> Optional[Dict[str, Any]]:
        """Read JSON file safely."""
        p = Path(filepath)
        if not p.exists():
            logger.warning("JSON file not found: %s", p)
            return None

        try:
            with open(p, "r", encoding="utf-8") as f:
                data = json.load(f)
            return sanitize_value(data)
        except Exception as e:
            logger.error("Failed to read JSON %s: %s", p, e)
            return None

    @staticmethod
    def read_jsonl(
        filepath: Union[str, Path],
        limit: Optional[int] = None,
        offset: Optional[int] = None,
        id_field: Optional[str] = None,
        target_id: Optional[str] = None,
    ) -> Tuple[List[Dict[str, Any]], int]:
        """Read JSON Lines file with pagination or ID search.

        Returns:
            Tuple of (records, total_matching_records).
        """
        p = Path(filepath)
        if not p.exists():
            logger.warning("JSONL file not found: %s", p)
            return [], 0

        try:
            matched_records = []
            with open(p, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        record = json.loads(line)
                        if id_field and target_id is not None:
                            if str(record.get(id_field, "")).strip().upper() == str(target_id).strip().upper():
                                matched_records.append(record)
                        else:
                            matched_records.append(record)
                    except Exception:
                        pass

            total = len(matched_records)
            start = offset or 0
            if limit is not None:
                page = matched_records[start : start + limit]
            else:
                page = matched_records[start:]

            sanitized_page = [sanitize_value(r) for r in page]
            return sanitized_page, total
        except Exception as e:
            logger.error("Failed to read JSONL %s: %s", p, e)
            return [], 0

